"""Preview one official LIBERO scene and save a deterministic camera video.

Run this script only with ``.venv-libero``.  It deliberately has no import
from the robosuite 1.5 mainline: LIBERO keeps its official robosuite 1.4
dependency in a separate environment.  The preview applies exact zero actions
and proves scene loading / recording only; it is not a task-success claim or
a SpaceMouse teleoperation adapter.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys
from typing import Any

import numpy as np


ROOT = Path(__file__).resolve().parents[1]


def _configure_local_libero_paths() -> None:
    """Avoid LIBERO's interactive first-import prompt on a shared workstation."""

    config_root = ROOT / "outputs" / "libero" / ".libero_config"
    config_root.mkdir(parents=True, exist_ok=True)
    dataset_root = config_root / "datasets"
    dataset_root.mkdir(exist_ok=True)
    source_root = ROOT / "third_party" / "LIBERO" / "libero" / "libero"
    paths = {
        "benchmark_root": str(source_root),
        "bddl_files": str(source_root / "bddl_files"),
        "init_states": str(source_root / "init_files"),
        "datasets": str(dataset_root),
        "assets": str(source_root / "assets"),
    }
    (config_root / "config.yaml").write_text(json.dumps(paths, indent=2), encoding="utf-8")
    os.environ["LIBERO_CONFIG_PATH"] = str(config_root)
    # robosuite 1.4 accepts WGL, rather than EGL, on Windows. A parent shell
    # may retain MUJOCO_GL=egl from Linux-oriented tooling.
    if os.name == "nt":
        os.environ["MUJOCO_GL"] = "wgl"


def _ensure_windows_robosuite_mujoco_dll() -> None:
    """Supply robosuite 1.4's documented Windows DLL lookup without source edits.

    robosuite 1.4 imports ``robosuite/utils/mujoco.dll`` on Windows while the
    current official ``mujoco`` wheel installs that DLL in its own package.
    Copying this binary compatibility asset into the *isolated LIBERO venv*
    makes the old lookup resolve.  The 1.5 mainline venv is never touched.
    """

    if os.name != "nt":
        return
    site_packages = Path(sys.prefix) / "Lib" / "site-packages"
    source = site_packages / "mujoco" / "mujoco.dll"
    target = site_packages / "robosuite" / "utils" / "mujoco.dll"
    if not source.is_file():
        raise RuntimeError(f"LIBERO MuJoCo DLL is missing: {source}")
    digest = lambda path: hashlib.sha256(path.read_bytes()).digest()
    if target.is_file() and digest(target) == digest(source):
        return
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(source, target)


def _ensure_windows_robosuite_render_config() -> None:
    """Install only robosuite's supported private-macro override in the LIBERO venv."""

    if os.name != "nt":
        return
    macros_private = Path(sys.prefix) / "Lib" / "site-packages" / "robosuite" / "macros_private.py"
    generated = (
        "# Generated by run_libero_task_preview.py for Windows WGL support.\n"
        "import robosuite.macros as _robosuite_macros\n"
        "_robosuite_macros.MUJOCO_GPU_RENDERING = False\n"
    )
    if macros_private.exists() and not macros_private.read_text(encoding="utf-8").startswith(
        "# Generated by run_libero_task_preview.py"
    ):
        return
    macros_private.write_text(generated, encoding="utf-8")


def _write_video(path: Path, frames: list[np.ndarray], fps: int) -> str:
    import cv2

    if not frames:
        raise RuntimeError("LIBERO supplied no agentview frames")
    path.parent.mkdir(parents=True, exist_ok=True)
    height, width = frames[0].shape[:2]
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"mp4v"), fps, (width, height))
    if not writer.isOpened():
        writer.release()
        directory = path.with_suffix("").with_name(f"{path.stem}_frames")
        directory.mkdir(parents=True, exist_ok=True)
        for index, frame in enumerate(frames):
            if not cv2.imwrite(str(directory / f"{index:06d}.png"), frame[:, :, ::-1]):
                raise RuntimeError("could not write LIBERO PNG fallback")
        return str(directory)
    try:
        for frame in frames:
            writer.write(frame[:, :, ::-1])
    finally:
        writer.release()
    return str(path)


def run_preview(args: argparse.Namespace) -> dict[str, Any]:
    _configure_local_libero_paths()
    _ensure_windows_robosuite_mujoco_dll()
    _ensure_windows_robosuite_render_config()
    try:
        import torch
        from libero.libero import get_libero_path
        from libero.libero.benchmark import get_benchmark
        from libero.libero.envs import OffScreenRenderEnv
    except ImportError as exc:
        raise RuntimeError(
            "LIBERO dependencies are unavailable. Run this script with .venv-libero after its setup completes."
        ) from exc

    benchmark = get_benchmark(args.suite)(args.task_order)
    if not 0 <= args.task_id < benchmark.get_num_tasks():
        raise ValueError(f"task id {args.task_id} is outside 0..{benchmark.get_num_tasks() - 1}")
    task = benchmark.get_task(args.task_id)
    env = OffScreenRenderEnv(
        bddl_file_name=str(Path(get_libero_path("bddl_files")) / task.problem_folder / task.bddl_file),
        camera_heights=args.height,
        camera_widths=args.width,
        camera_names=["agentview", "robot0_eye_in_hand"],
        control_freq=args.control_hz,
        horizon=max(args.steps + 10, 100),
    )
    try:
        env.seed(args.seed)
        env.reset()
        init_states = torch.load(
            Path(get_libero_path("init_states")) / task.problem_folder / task.init_states_file,
            map_location="cpu",
        )
        if not 0 <= args.init_state_id < len(init_states):
            raise ValueError(f"init state id {args.init_state_id} is outside 0..{len(init_states) - 1}")
        obs = env.set_init_state(init_states[args.init_state_id])
        # LIBERO's thin wrapper deliberately exposes only ``step``; the
        # underlying robosuite environment owns the actual action contract.
        action_spec = getattr(env, "action_spec", None)
        if action_spec is None:
            action_spec = env.env.action_spec
        action_dim = int(np.asarray(action_spec[0]).shape[0])
        action = np.zeros(action_dim, dtype=np.float32)
        frames: list[np.ndarray] = []
        success_seen = False
        for _ in range(args.steps):
            image = np.asarray(obs["agentview_image"], dtype=np.uint8)
            frames.append(np.ascontiguousarray(image[::-1, :, :3]))
            obs, _reward, _done, _info = env.step(action)
            success_seen = bool(success_seen or env.check_success())
        output = _write_video(args.record, frames, args.control_hz)
        return {
            "mode": "official_libero_zero_action_scene_preview",
            "suite": args.suite,
            "task_id": args.task_id,
            "task_name": task.name,
            "language": task.language,
            "init_state_id": args.init_state_id,
            "seed": args.seed,
            "action_dim": action_dim,
            "action_policy": "exact_zero",
            "steps": args.steps,
            "frames": len(frames),
            "success_seen": success_seen,
            "recording": output,
            "note": "Scene-loading and recording check only; this does not evaluate task success or SpaceMouse control.",
        }
    finally:
        env.close()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite", default="libero_spatial", choices=("libero_spatial", "libero_object", "libero_goal", "libero_10", "libero_90"))
    parser.add_argument("--task-order", type=int, default=0)
    parser.add_argument("--task-id", type=int, default=0)
    parser.add_argument("--init-state-id", type=int, default=0)
    parser.add_argument("--seed", type=int, default=7)
    parser.add_argument("--steps", type=int, default=120)
    parser.add_argument("--control-hz", type=int, default=20)
    parser.add_argument("--width", type=int, default=640)
    parser.add_argument("--height", type=int, default=480)
    parser.add_argument("--record", type=Path, default=ROOT / "outputs" / "libero" / "libero_spatial_task0_zero_action.mp4")
    args = parser.parse_args()
    if args.steps <= 0 or args.control_hz <= 0 or args.width <= 0 or args.height <= 0:
        parser.error("steps, control-hz, width, and height must be positive")
    return args


def main() -> int:
    args = parse_args()
    try:
        result = run_preview(args)
    except Exception as exc:
        print(f"LIBERO preview failed: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1
    metadata = args.record.with_suffix(".json")
    metadata.parent.mkdir(parents=True, exist_ok=True)
    metadata.write_text(json.dumps(result, indent=2), encoding="utf-8")
    print(json.dumps(result, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
